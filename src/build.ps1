function RoundG($n,$g){
  if($U.ContainsKey($n)){ $u=$U[$n]; $cnt=[math]::Max(1,[math]::Round($g/$u)); return $cnt*$u }
  if($g -lt 30){ return [math]::Max(1,[math]::Round($g)) }
  return [math]::Round($g/5)*5
}
function ScaleDay($mealItems,$target){
  for($pass=0; $pass -lt 6; $pass++){
    $tot=0.0
    foreach($mi in $mealItems){ $tot += (Calc $mi)[0] }
    $fixed = (Calc $mealItems[$mealItems.Count-1])[0]
    $flex = $tot - $fixed
    if($flex -le 0){ break }
    $fac = ($target - $fixed)/$flex
    if([math]::Abs($fac-1) -lt 0.008){ break }
    for($j=0;$j -lt ($mealItems.Count-1);$j++){
      foreach($it in $mealItems[$j]){ $it[1] = RoundG $it[0] ($it[1]*$fac) }
    }
  }
}

# Его дневная норма больше её на 15%, но раскладка по приёмам этого не
# гарантировала: излишек оседал в одном приёме, а в соседнем его порция
# оказывалась меньше её. У плиты это читается как ошибка, поэтому каждый
# его приём подтягивается минимум до её уровня, а день пересчитывается в цель.
function Balance($wAll,$mAll,$targetM){
  $last = $mAll.Count-1
  for($pass=0; $pass -lt 8; $pass++){
    $moved = $false
    for($j=0; $j -lt $last; $j++){
      $wv = (Calc $wAll[$j])[0]; $mv = (Calc $mAll[$j])[0]
      if($mv -le 0 -or $wv -le 0){ continue }
      if($mv -ge $wv*1.02){ continue }
      $f = ($wv*1.06)/$mv
      foreach($it in $mAll[$j]){ $it[1] = RoundG $it[0] ($it[1]*$f) }
      $moved = $true
    }
    ScaleDay $mAll $targetM
    if(-not $moved){ break }
  }
}

